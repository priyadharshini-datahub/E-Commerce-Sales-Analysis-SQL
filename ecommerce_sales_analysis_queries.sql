-- Q21. Display each order with customer name and city
SELECT
    o.order_id,
    c.customer_name,
    c.city,
    o.order_date,
    o.order_status
FROM orders o
JOIN customers c
    ON o.customer_id = c.customer_id;


-- Q22. Display each order with product name, quantity and price
SELECT
    oi.order_id,
    p.product_name,
    oi.quantity,
    p.price
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id;


-- Q23. Find total revenue from Delivered orders only
SELECT
    SUM(p.price * oi.quantity) AS total_revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
WHERE o.order_status = 'Delivered';


-- Q24. Find total revenue generated by each customer
SELECT
    c.customer_name,
    SUM(p.price * oi.quantity) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
WHERE o.order_status = 'Delivered'
GROUP BY c.customer_id, c.customer_name
ORDER BY total_spending DESC;


-- Q25. Find the top 5 customers based on total spending
SELECT
    c.customer_name,
    SUM(p.price * oi.quantity) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
WHERE o.order_status = 'Delivered'
GROUP BY c.customer_id, c.customer_name
ORDER BY total_spending DESC
LIMIT 5;


-- Q26. Find customers whose total spending is greater than ₹50,000
SELECT
    c.customer_name,
    SUM(p.price * oi.quantity) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
WHERE o.order_status = 'Delivered'
GROUP BY c.customer_id, c.customer_name
HAVING SUM(p.price * oi.quantity) > 50000;


-- Q27. Find the product with the highest total revenue
SELECT
    p.product_name,
    SUM(p.price * oi.quantity) AS total_revenue
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.order_status = 'Delivered'
GROUP BY p.product_id, p.product_name
ORDER BY total_revenue DESC
LIMIT 1;


-- Q28. Find customers who have never placed an order
SELECT
    c.customer_id,
    c.customer_name
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;


-- Q29. Categorize products based on price
SELECT
    product_name,
    price,
    CASE
        WHEN price > 20000 THEN 'Premium'
        WHEN price >= 5000 THEN 'Mid-Range'
        ELSE 'Budget'
    END AS price_category
FROM products;


-- Q30. Find monthly revenue from Delivered orders
SELECT
    DATE_FORMAT(o.order_date, '%Y-%m') AS sales_month,
    SUM(p.price * oi.quantity) AS monthly_revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
WHERE o.order_status = 'Delivered'
GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
ORDER BY sales_month;