-- Q1. Display all customers
SELECT *
FROM customers;


-- Q2. Find customers from Coimbatore
SELECT *
FROM customers
WHERE city = 'Coimbatore';


-- Q3. Find products with price greater than ₹5,000
SELECT *
FROM products
WHERE price > 5000;


-- Q4. Display products from highest to lowest price
SELECT *
FROM products
ORDER BY price DESC;


-- Q5. Find the total number of customers
